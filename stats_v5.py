# Resampling functions
# ============================================================

def resample_step_values(events: list[tuple[float, Any]], times: list[float], fill_before_first: str = "blank") -> list[Any]:
    events = sorted(events, key=lambda x: x[0])
    values: list[Any] = []
    index = 0
    current: Any = ""

    if fill_before_first == "first" and events:
        current = events[0][1]

    for t_sec in times:
        while index < len(events) and events[index][0] <= t_sec + 1e-9:
            current = events[index][1]
            index += 1
        values.append(current)

    return values


def resample_ti_trial(trial: TrialData, slider_label: str, times: list[float]) -> list[str]:
    events: list[tuple[float, float]] = []

    for row in sorted_rows_by_time(trial.rows):
        if str(row.get("input_type", "")).strip().lower() != "slider":
            continue

        label = str(row.get("input_label", "")).strip() or str(row.get("input_id", "")).strip()
        if label != slider_label:
            continue

        t = parse_float(row.get("t_sec", ""), None)
        v = parse_float(row.get("value", ""), None)
        if t is None or v is None:
            continue

        events.append((t, v))

    sampled = resample_step_values(events, times, FILL_BEFORE_FIRST_SLIDER_VALUE)

    result = []
    for t_sec, value in zip(times, sampled):
        if not is_trial_valid_at_time(trial, t_sec):
            result.append("")
        elif value == "":
            result.append("")
        else:
            result.append(format_number(float(value)))

    return result


def resample_tds_trial(trial: TrialData, times: list[float], value_mode: str) -> list[str]:
    events: list[tuple[float, str, bool | None]] = []

    for row in sorted_rows_by_time(trial.rows):
        if str(row.get("input_type", "")).strip().lower() != "button":
            continue

        item = get_item_value(row, value_mode)
        if not item:
            continue

        t = parse_float(row.get("t_sec", ""), None)
        if t is None:
            continue

        on_state = parse_bool_like(row.get("value", ""))
        event_name = str(row.get("event", "")).strip().lower()

        if on_state is None:
            # In TDS, a button event without an explicit 0/1 value is treated as a selection.
            if event_name in {"off", "unselect", "unselected", "clear"}:
                on_state = False
            else:
                on_state = True

        events.append((t, item, on_state))

    events = sorted(events, key=lambda x: x[0])
    sampled: list[str] = []
    current = ""
    index = 0

    for t_sec in times:
        while index < len(events) and events[index][0] <= t_sec + 1e-9:
            _, item, on_state = events[index]
            if on_state:
                current = item
            elif current == item:
                current = ""
            index += 1

        if is_trial_valid_at_time(trial, t_sec):
            sampled.append(current)
        else:
            sampled.append("")

    return sampled


def resample_tcata_trial(trial: TrialData, times: list[float], value_mode: str) -> dict[str, list[int | str]]:
    events: list[tuple[float, str, bool | None]] = []

    for row in sorted_rows_by_time(trial.rows):
        if str(row.get("input_type", "")).strip().lower() != "button":
            continue

        item = get_item_value(row, value_mode)
        if not item:
            continue

        t = parse_float(row.get("t_sec", ""), None)
        if t is None:
            continue

        on_state = parse_bool_like(row.get("value", ""))
        events.append((t, item, on_state))

    events = sorted(events, key=lambda x: x[0])
    state: set[str] = set()
    index = 0
    all_items = sorted({item for _, item, _ in events})
    sampled = {item: [] for item in all_items}

    for t_sec in times:
        while index < len(events) and events[index][0] <= t_sec + 1e-9:
            _, item, on_state = events[index]

            if on_state is None:
                # If no explicit state is supplied, treat the event as a toggle.
                if item in state:
                    state.remove(item)
                else:
                    state.add(item)
            elif on_state:
                state.add(item)
            else:
                state.discard(item)

            index += 1

        for item in all_items:
            if is_trial_valid_at_time(trial, t_sec):
                sampled[item].append(1 if item in state else 0)
            else:
                sampled[item].append("")

    return sampled


