def clear_generated_outputs(group_dir: Path) -> None:
    """Remove only CSV files that this script is responsible for generating."""
    if not group_dir.exists():
        return

    for pattern in GENERATED_FILE_PATTERNS:
        for path in group_dir.glob(pattern):
            if path.is_file():
                path.unlink()


def write_table_csv(path: Path, header: list[str], rows: list[list[Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding=CSV_OUTPUT_ENCODING, errors="replace") as f:
        writer = csv.writer(f)
        writer.writerow(header)
        writer.writerows(rows)


def group_trials(trials: list[TrialData], group_by: list[str]) -> dict[str, list[TrialData]]:
    if not group_by:
        return {"all": trials}

    groups: dict[str, list[TrialData]] = {}

    for trial in trials:
        parts = []
        for key in group_by:
            value = trial.meta.get(key, "").strip() or "unknown"
            parts.append(f"{key}_{value}")

        group_name = safe_name("__".join(parts), "group")
        groups.setdefault(group_name, []).append(trial)

    return groups


def trial_column_name(trial: TrialData) -> str:
    return safe_name(trial.trial_id or trial.trial_dir.name)


