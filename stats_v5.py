def make_time_axis(trials: list[TrialData], sampling_rate_hz: float, mode: str) -> list[float]:
    durations = [trial.duration_sec for trial in trials if trial.duration_sec >= 0]
    if not durations:
        return [0.0]

    mode = mode.strip().lower()
    if mode == "min_duration":
        end_time = min(durations)
    elif mode == "max_duration":
        end_time = max(durations)
    else:
        raise ValueError("TIME_RANGE_MODE must be 'min_duration' or 'max_duration'")

    step = 1.0 / sampling_rate_hz
    n_steps = int(math.floor(end_time * sampling_rate_hz + 1e-9))
    return [round(i * step, 10) for i in range(n_steps + 1)]


def is_trial_valid_at_time(trial: TrialData, t_sec: float) -> bool:
    return t_sec <= trial.duration_sec + 1e-9


