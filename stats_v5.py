def export_group_outputs(output_dir: Path, group_name: str, trials: list[TrialData], sampling_rate_hz: float, time_range_mode: str) -> list[Path]:
    group_dir = output_dir / group_name
    clear_generated_outputs(group_dir)
    times = make_time_axis(trials, sampling_rate_hz, time_range_mode)
    output_paths: list[Path] = []

    if EXPORT_TI_RAW:
        output_paths.extend(export_ti_raw(group_dir, trials, times, sampling_rate_hz))

    if EXPORT_TI_MEAN or EXPORT_TI_SD:
        output_paths.extend(export_ti_mean_sd(group_dir, trials, times, sampling_rate_hz))

    if EXPORT_TDS_RAW:
        output_paths.extend(export_tds_raw(group_dir, trials, times, sampling_rate_hz))

    if EXPORT_TDS_RATE:
        output_paths.extend(export_tds_rate(group_dir, trials, times, sampling_rate_hz))

    if EXPORT_TCATA_RATE:
        output_paths.extend(export_tcata_rate(group_dir, trials, times, sampling_rate_hz))

    return output_paths


def write_manifest(output_dir: Path, root_dir: Path, trials: list[TrialData], output_paths: list[Path], sampling_rate_hz: float, time_range_mode: str, group_by: list[str]) -> None:
    lines = [
        "TimeSenseApp stats_v5 output",
        "",
        f"root_dir: {root_dir}",
        f"output_dir: {output_dir}",
        f"n_trials: {len(trials)}",
        f"sampling_rate_hz: {sampling_rate_hz}",
        f"time_range_mode: {time_range_mode}",
        f"group_by: {', '.join(group_by) if group_by else 'none'}",
        f"tds_raw_value: {TDS_RAW_VALUE}",
        f"rate_item_value: {RATE_ITEM_VALUE}",
        f"export_ti_raw: {EXPORT_TI_RAW}",
        f"export_ti_mean: {EXPORT_TI_MEAN}",
        f"export_ti_sd: {EXPORT_TI_SD}",
        f"export_tds_raw: {EXPORT_TDS_RAW}",
        f"export_tds_rate: {EXPORT_TDS_RATE}",
        f"export_tcata_rate: {EXPORT_TCATA_RATE}",
        f"csv_output_encoding: {CSV_OUTPUT_ENCODING}",
        "stale_generated_csv_cleanup: enabled",
        "",
        "input_trials:",
    ]

    for trial in trials:
        lines.append(f"- {trial.trial_dir.name} | trial_id={trial.trial_id} | mode={trial.selection_mode} | duration_sec={trial.duration_sec}")

    lines.extend(["", "output_files:"])
    for path in output_paths:
        try:
            rel = path.relative_to(output_dir)
        except Exception:
            rel = path
        lines.append(f"- {rel}")

    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "manifest.txt").write_text("\n".join(lines) + "\n", encoding=CSV_OUTPUT_ENCODING, errors="replace")


def run_stats(
    root_dir: str | Path,
    output_dir: str | Path,
    sampling_rate_hz: float = SAMPLING_RATE_HZ,
    time_range_mode: str = TIME_RANGE_MODE,
    group_by: list[str] | str | None = None,
    trial_dirs: list[str | Path] | None = None,
    tds_raw_value: str = TDS_RAW_VALUE,
    rate_item_value: str = RATE_ITEM_VALUE,
    export_ti_raw: bool | None = None,
    export_ti_mean: bool | None = None,
    export_ti_sd: bool | None = None,
    export_tds_raw: bool | None = None,
    export_tds_rate: bool | None = None,
    export_tcata_rate: bool | None = None,
    save_config: bool = True,
) -> StatsRunResult:
    """Create graph-ready CSV files from TimeSenseApp trial folders.

    This function is intended for both CLI use and launcher GUI integration.
    It writes CSV files only; no graph image files are generated.
    """
    global TDS_RAW_VALUE, RATE_ITEM_VALUE
    global EXPORT_TI_RAW, EXPORT_TI_MEAN, EXPORT_TI_SD, EXPORT_TDS_RAW, EXPORT_TDS_RATE, EXPORT_TCATA_RATE

    root_path = expand_path(root_dir)
    output_path = expand_path(output_dir)

    if not root_path.exists():
        raise FileNotFoundError(f"Input folder does not exist: {root_path}")

    sampling_rate_hz = float(sampling_rate_hz)
    if sampling_rate_hz <= 0:
        raise ValueError("sampling_rate_hz must be > 0")

    time_range_mode = str(time_range_mode).strip().lower()
    if time_range_mode not in {"min_duration", "max_duration"}:
        raise ValueError("time_range_mode must be 'min_duration' or 'max_duration'")

    tds_raw_value = str(tds_raw_value).strip()
    rate_item_value = str(rate_item_value).strip()
    if tds_raw_value not in {"input_id", "input_label"}:
        raise ValueError("tds_raw_value must be 'input_id' or 'input_label'")
    if rate_item_value not in {"input_id", "input_label"}:
        raise ValueError("rate_item_value must be 'input_id' or 'input_label'")

    TDS_RAW_VALUE = tds_raw_value
    RATE_ITEM_VALUE = rate_item_value

    if export_ti_raw is not None:
        EXPORT_TI_RAW = bool(export_ti_raw)
    if export_ti_mean is not None:
        EXPORT_TI_MEAN = bool(export_ti_mean)
    if export_ti_sd is not None:
        EXPORT_TI_SD = bool(export_ti_sd)
    if export_tds_raw is not None:
        EXPORT_TDS_RAW = bool(export_tds_raw)
    if export_tds_rate is not None:
        EXPORT_TDS_RATE = bool(export_tds_rate)
    if export_tcata_rate is not None:
        EXPORT_TCATA_RATE = bool(export_tcata_rate)

    if group_by is None:
        group_by_list = list(GROUP_BY)
    elif isinstance(group_by, str):
        group_by_text = group_by.strip()
        if group_by_text.lower() in {"", "all", "none", "no grouping"}:
            group_by_list = []
        else:
            group_by_list = [item.strip() for item in group_by_text.split(",") if item.strip()]
    else:
        group_by_list = [str(item).strip() for item in group_by if str(item).strip()]

    trial_dir_paths = None
    if trial_dirs:
        trial_dir_paths = [expand_path(path_text) for path_text in trial_dirs]

    trials = load_trials(root_path, trial_dirs=trial_dir_paths)
    if not trials:
        raise ValueError(f"No trial folders containing data.csv were found: {root_path}")

    output_paths: list[Path] = []
    groups = group_trials(trials, group_by_list)

    for group_name, group_trials_list in groups.items():
        output_paths.extend(
            export_group_outputs(
                output_dir=output_path,
                group_name=group_name,
                trials=group_trials_list,
                sampling_rate_hz=sampling_rate_hz,
                time_range_mode=time_range_mode,
            )
        )

    write_manifest(
        output_dir=output_path,
        root_dir=root_path,
        trials=trials,
        output_paths=output_paths,
        sampling_rate_hz=sampling_rate_hz,
        time_range_mode=time_range_mode,
        group_by=group_by_list,
    )

    if save_config:
        save_stats_config(
            {
                "root_dir": str(root_path),
                "output_dir": str(output_path),
                "sampling_rate_hz": sampling_rate_hz,
                "time_range_mode": time_range_mode,
                "group_by": ",".join(group_by_list),
                "tds_raw_value": tds_raw_value,
                "rate_item_value": rate_item_value,
                "export_ti_raw": EXPORT_TI_RAW,
                "export_ti_mean": EXPORT_TI_MEAN,
                "export_ti_sd": EXPORT_TI_SD,
                "export_tds_raw": EXPORT_TDS_RAW,
                "export_tds_rate": EXPORT_TDS_RATE,
                "export_tcata_rate": EXPORT_TCATA_RATE,
            }
        )

    return StatsRunResult(
        root_dir=root_path,
        output_dir=output_path,
        n_trials=len(trials),
        n_output_files=len(output_paths),
        output_paths=output_paths,
        manifest_path=output_path / "manifest.txt",
    )


def parse_args() -> argparse.Namespace:
    config = load_stats_config()

    parser = argparse.ArgumentParser(
        description="Create graph-ready CSV files from TimeSenseApp trial folders."
    )
    parser.add_argument("--root", type=str, default=None, help="Parent folder containing trial folders.")
    parser.add_argument("--output", type=str, default=None, help="Output folder for CSV files.")
    parser.add_argument("--sampling-rate", type=float, default=float(config.get("sampling_rate_hz", SAMPLING_RATE_HZ)), help="Sampling rate in Hz.")
    parser.add_argument(
        "--time-range-mode",
        type=str,
        default=str(config.get("time_range_mode", TIME_RANGE_MODE)),
        choices=["min_duration", "max_duration"],
        help="Time range used for output time axis.",
    )
    parser.add_argument(
        "--group-by",
        type=str,
        default=str(config.get("group_by", ",".join(GROUP_BY))),
        help="Comma-separated metadata fields for grouping, e.g. sample_id or subject_id,sample_id. Empty string means all trials together.",
    )
    parser.add_argument(
        "--tds-raw-value",
        type=str,
        default=str(config.get("tds_raw_value", TDS_RAW_VALUE)),
        choices=["input_id", "input_label"],
        help="Value written in TDS_raw.csv cells.",
    )
    parser.add_argument(
        "--rate-item-value",
        type=str,
        default=str(config.get("rate_item_value", RATE_ITEM_VALUE)),
        choices=["input_id", "input_label"],
        help="Column labels used in TDS_rate.csv and TCATA_rate.csv.",
    )
    parser.add_argument(
        "--trial-dirs",
        type=str,
        nargs="*",
        default=None,
        help="Optional explicit trial folders. If omitted, all child folders containing data.csv are used.",
    )
    parser.add_argument("--no-ti-raw", action="store_true", help="Do not export TI_raw_*.csv files.")
    parser.add_argument("--no-ti-mean", action="store_true", help="Do not export TI_mean.csv.")
    parser.add_argument("--no-ti-sd", action="store_true", help="Do not export TI_sd.csv.")
    parser.add_argument("--no-tds-raw", action="store_true", help="Do not export TDS_raw.csv.")
    parser.add_argument("--no-tds-rate", action="store_true", help="Do not export TDS_rate.csv.")
    parser.add_argument("--no-tcata-rate", action="store_true", help="Do not export TCATA_rate.csv.")
    parser.add_argument(
        "--no-dialog",
        action="store_true",
        help="Do not open a folder-selection dialog when --root is omitted.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    config = load_stats_config()

    if args.root:
        root_dir = expand_path(args.root)
    elif USE_FOLDER_DIALOG_IF_NO_ROOT and not args.no_dialog:
        selected = select_root_folder_by_dialog()
        root_dir = selected if selected is not None else expand_path(str(config.get("root_dir", ROOT_DIR)))
    else:
        root_dir = expand_path(str(config.get("root_dir", ROOT_DIR)))

    if args.output:
        output_dir = expand_path(args.output)
    else:
        output_dir = expand_path(str(config.get("output_dir", OUTPUT_DIR)))

    trial_dirs = None
    if args.trial_dirs:
        trial_dirs = [expand_path(path_text) for path_text in args.trial_dirs]

    try:
        result = run_stats(
            root_dir=root_dir,
            output_dir=output_dir,
            sampling_rate_hz=float(args.sampling_rate),
            time_range_mode=args.time_range_mode,
            group_by=args.group_by,
            trial_dirs=trial_dirs,
            tds_raw_value=args.tds_raw_value,
            rate_item_value=args.rate_item_value,
            export_ti_raw=not args.no_ti_raw,
            export_ti_mean=not args.no_ti_mean,
            export_ti_sd=not args.no_ti_sd,
            export_tds_raw=not args.no_tds_raw,
            export_tds_rate=not args.no_tds_rate,
            export_tcata_rate=not args.no_tcata_rate,
            save_config=True,
        )
    except Exception as exc:
        print(f"Error: {exc}")
        sys.exit(1)

    print("Done.")
    print(f"Input trials: {result.n_trials}")
    print(f"Output files: {result.n_output_files}")
    print(f"Output folder: {result.output_dir}")


if __name__ == "__main__":
    main()
