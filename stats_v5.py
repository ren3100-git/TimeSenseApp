def get_item_value(row: dict[str, str], value_mode: str) -> str:
    input_id = str(row.get("input_id", "")).strip()
    input_label = str(row.get("input_label", "")).strip()

    if value_mode == "input_id":
        return input_id
    if value_mode == "input_label":
        return input_label or input_id

    raise ValueError("value_mode must be 'input_id' or 'input_label'")


def sorted_rows_by_time(rows: list[dict[str, str]]) -> list[dict[str, str]]:
    return sorted(rows, key=lambda row: parse_float(row.get("t_sec", ""), 0.0) or 0.0)


def collect_slider_labels(trials: list[TrialData]) -> list[str]:
    labels: set[str] = set()
    for trial in trials:
        for row in trial.rows:
            if str(row.get("input_type", "")).strip().lower() != "slider":
                continue
            label = str(row.get("input_label", "")).strip() or str(row.get("input_id", "")).strip()
            if label:
                labels.add(label)
    return sorted(labels)


def collect_button_items(trials: list[TrialData], value_mode: str) -> list[str]:
    items: set[str] = set()
    for trial in trials:
        for row in trial.rows:
            if str(row.get("input_type", "")).strip().lower() != "button":
                continue
            item = get_item_value(row, value_mode)
            if item:
                items.add(item)
    return sorted(items)


