def export_ti_raw(group_dir: Path, trials: list[TrialData], times: list[float], sampling_rate_hz: float) -> list[Path]:
    output_paths: list[Path] = []
    slider_labels = collect_slider_labels(trials)

    for slider_label in slider_labels:
        header = ["t_sec"] + [trial_column_name(trial) for trial in trials]
        sampled_by_trial = [resample_ti_trial(trial, slider_label, times) for trial in trials]

        rows = []
        for i, t_sec in enumerate(times):
            row = [time_key(t_sec, sampling_rate_hz)]
            row.extend(sampled[i] for sampled in sampled_by_trial)
            rows.append(row)

        path = group_dir / f"TI_raw_{safe_name(slider_label)}.csv"
        write_table_csv(path, header, rows)
        output_paths.append(path)

    return output_paths


def export_ti_mean_sd(group_dir: Path, trials: list[TrialData], times: list[float], sampling_rate_hz: float) -> list[Path]:
    output_paths: list[Path] = []
    slider_labels = collect_slider_labels(trials)

    if not slider_labels:
        return output_paths

    sampled_by_label: dict[str, list[list[str]]] = {}
    for slider_label in slider_labels:
        sampled_by_label[slider_label] = [resample_ti_trial(trial, slider_label, times) for trial in trials]

    if EXPORT_TI_MEAN:
        header = ["t_sec"] + slider_labels
        rows = []
        for i, t_sec in enumerate(times):
            row = [time_key(t_sec, sampling_rate_hz)]
            for slider_label in slider_labels:
                values = [parse_float(sampled[i], math.nan) for sampled in sampled_by_label[slider_label]]
                row.append(format_number(mean([v for v in values if v is not None])))
            rows.append(row)

        path = group_dir / "TI_mean.csv"
        write_table_csv(path, header, rows)
        output_paths.append(path)

    if EXPORT_TI_SD:
        header = ["t_sec"] + slider_labels
        rows = []
        for i, t_sec in enumerate(times):
            row = [time_key(t_sec, sampling_rate_hz)]
            for slider_label in slider_labels:
                values = [parse_float(sampled[i], math.nan) for sampled in sampled_by_label[slider_label]]
                row.append(format_number(sample_sd([v for v in values if v is not None])))
            rows.append(row)

        path = group_dir / "TI_sd.csv"
        write_table_csv(path, header, rows)
        output_paths.append(path)

    return output_paths


