def export_tcata_rate(group_dir: Path, trials: list[TrialData], times: list[float], sampling_rate_hz: float) -> list[Path]:
    tcata_trials = [trial for trial in trials if trial.selection_mode == "tcata"]
    if not tcata_trials:
        return []

    items = collect_button_items(tcata_trials, RATE_ITEM_VALUE)
    if not items:
        return []

    sampled_by_trial = [resample_tcata_trial(trial, times, RATE_ITEM_VALUE) for trial in tcata_trials]

    header = ["t_sec"] + items
    rows = []

    for i, t_sec in enumerate(times):
        valid_trial_indices = [j for j, trial in enumerate(tcata_trials) if is_trial_valid_at_time(trial, t_sec)]
        n_valid = len(valid_trial_indices)
        row = [time_key(t_sec, sampling_rate_hz)]

        for item in items:
            if n_valid == 0:
                row.append("")
                continue

            count = 0
            for j in valid_trial_indices:
                trial_sampled = sampled_by_trial[j]
                values = trial_sampled.get(item, [])
                if i < len(values) and values[i] == 1:
                    count += 1

            row.append(format_number(count / n_valid))

        rows.append(row)

    path = group_dir / "TCATA_rate.csv"
    write_table_csv(path, header, rows)
    return [path]


