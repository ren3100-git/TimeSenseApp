def export_tds_raw(group_dir: Path, trials: list[TrialData], times: list[float], sampling_rate_hz: float) -> list[Path]:
    tds_trials = [trial for trial in trials if trial.selection_mode == "tds"]
    if not tds_trials:
        return []

    header = ["t_sec"] + [trial_column_name(trial) for trial in tds_trials]
    sampled_by_trial = [resample_tds_trial(trial, times, TDS_RAW_VALUE) for trial in tds_trials]

    rows = []
    for i, t_sec in enumerate(times):
        row = [time_key(t_sec, sampling_rate_hz)]
        row.extend(sampled[i] for sampled in sampled_by_trial)
        rows.append(row)

    path = group_dir / "TDS_raw.csv"
    write_table_csv(path, header, rows)
    return [path]


def export_tds_rate(group_dir: Path, trials: list[TrialData], times: list[float], sampling_rate_hz: float) -> list[Path]:
    tds_trials = [trial for trial in trials if trial.selection_mode == "tds"]
    if not tds_trials:
        return []

    items = collect_button_items(tds_trials, RATE_ITEM_VALUE)
    if not items:
        return []

    sampled_by_trial = [resample_tds_trial(trial, times, RATE_ITEM_VALUE) for trial in tds_trials]

    header = ["t_sec"] + items
    rows = []

    for i, t_sec in enumerate(times):
        valid_trial_indices = [j for j, trial in enumerate(tds_trials) if is_trial_valid_at_time(trial, t_sec)]
        n_valid = len(valid_trial_indices)
        row = [time_key(t_sec, sampling_rate_hz)]

        for item in items:
            if n_valid == 0:
                row.append("")
                continue
            count = sum(1 for j in valid_trial_indices if sampled_by_trial[j][i] == item)
            row.append(format_number(count / n_valid))

        rows.append(row)

    path = group_dir / "TDS_rate.csv"
    write_table_csv(path, header, rows)
    return [path]


