def expand_path(path_text: str | Path) -> Path:
    return Path(path_text).expanduser().resolve()


def safe_name(text: Any, default: str = "untitled") -> str:
    text = str(text).strip()
    if not text:
        text = default
    text = re.sub(r"[^\w\-]+", "_", text)
    text = text.strip("_")
    return text or default


def parse_float(value: Any, default: float | None = None) -> float | None:
    try:
        text = str(value).strip()
        if text == "":
            return default
        return float(text)
    except Exception:
        return default


def parse_bool_like(value: Any) -> bool | None:
    text = str(value).strip().lower()
    if text == "":
        return None

    if text in {"1", "true", "t", "yes", "y", "on", "selected"}:
        return True
    if text in {"0", "false", "f", "no", "n", "off", "unselected"}:
        return False

    number = parse_float(text, None)
    if number is not None:
        return bool(number)

    return None


def time_key(value: float, sampling_rate_hz: float) -> str:
    # Decimal places sufficient for ordinary sampling rates such as 1, 2, 5, 10, 20, 50 Hz.
    if sampling_rate_hz <= 0:
        raise ValueError("SAMPLING_RATE_HZ must be > 0")

    decimals = max(0, int(math.ceil(-math.log10(1.0 / sampling_rate_hz))) + 2)
    text = f"{value:.{decimals}f}"
    text = text.rstrip("0").rstrip(".")
    return text if text else "0"


def mean(values: list[float]) -> float | None:
    values = [v for v in values if v is not None and not math.isnan(v)]
    if not values:
        return None
    return sum(values) / len(values)


def sample_sd(values: list[float]) -> float | None:
    values = [v for v in values if v is not None and not math.isnan(v)]
    n = len(values)
    if n <= 1:
        return None
    m = sum(values) / n
    return math.sqrt(sum((v - m) ** 2 for v in values) / (n - 1))


def format_number(value: float | None) -> str:
    if value is None:
        return ""
    if math.isnan(value):
        return ""
    text = f"{value:.10g}"
    return text


def load_json(path: Path, default: dict[str, Any]) -> dict[str, Any]:
    if not path.exists():
        save_json(path, default)
        return dict(default)

    try:
        with path.open("r", encoding="utf-8") as f:
            data = json.load(f)
        merged = dict(default)
        if isinstance(data, dict):
            merged.update(data)
        return merged
    except Exception:
        return dict(default)


def save_json(path: Path, data: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)


def read_text_with_fallback(path: Path) -> str:
    for encoding in CSV_READ_ENCODINGS:
        try:
            return path.read_text(encoding=encoding)
        except UnicodeDecodeError:
            continue

    return path.read_text(encoding=CSV_READ_ENCODINGS[-1], errors="replace")


def read_csv_dicts_with_fallback(path: Path) -> list[dict[str, str]]:
    for encoding in CSV_READ_ENCODINGS:
        try:
            with path.open("r", newline="", encoding=encoding) as f:
                reader = csv.DictReader(f)
                return [dict(row) for row in reader]
        except UnicodeDecodeError:
            continue

    with path.open("r", newline="", encoding=CSV_READ_ENCODINGS[-1], errors="replace") as f:
        reader = csv.DictReader(f)
        return [dict(row) for row in reader]


